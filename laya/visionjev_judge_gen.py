def _flow(rng):
    sk = rng.choice(FLOW)
    p = Prob("flow", sk["dom"])
    money = sk["u"] == "$"
    Q = M if money else Fmt("n", suf=" " + sk["u"])
    T = Fmt("n", suf=" " + sk["pers"])
    dp, tdp = sk["dp"], sk["tdp"]
    two = rng.random() < 0.35
    pause = not two and rng.random() < 0.45
    cap, out = rng.random() < 0.5, rng.random() < (0.35 if two else 0.5)
    r1, t1 = _dec(rng, *sk["r"], dp), _dec(rng, 3, 14, tdp)
    r2, t2 = _dec(rng, *sk["r"], dp), _dec(rng, 3, 14, tdp)
    pz = _dec(rng, 1, float(t1) - 1.5, tdp) if pause else D(0)
    loss = r1 * (t1 - pz) + (r2 * t2 if two else 0)
    unit = D("0.01") if money else D(1)
    S = (loss * _dec(rng, 1.3, 3.2, 2)).quantize(unit)
    A = (S * _dec(rng, 0.15, 0.6, 2)).quantize(unit)
    C = (S + A + loss * _dec(rng, 0.2, 1.5, 2)).quantize(unit)
    B = ((S - loss + A) * _dec(rng, 0.1, 0.45, 2)).quantize(unit)
    R = {"org": rng.choice(ORGS), "name": _person(rng), "S": p.giv("S", S, Q, "the starting amount")}
    if cap:
        R["C"] = p.giv("C", C, Q, "the capacity")
    R["r1"] = p.giv("r1", r1, Q, "the first rate" if two else "the rate")
    R["t1"] = p.giv("t1", t1, T, "the first duration" if two else "the duration")
    if two:
        R["r2"], R["t2"] = p.giv("r2", r2, Q, "the second rate"), p.giv("t2", t2, T, "the second duration")
    if pause:
        R["p"] = p.giv("p", pz, T, "the idle time")
    R["A"] = p.giv("A", A, Q, "the amount added")
    if out:
        R["B"] = p.giv("B", B, Q, "the amount taken out at the end")
    parts = [rng.choice(sk["start"])] + ([sk["cap"]] if cap else []) + [sk["loss"] + (sk["loss2"] if two else "") + "."]
    parts += ([sk["pause"]] if pause else []) + [sk["add"]] + ([sk["out"]] if out else []) + [sk["ask"], rng.choice(ASK)]
    p.request = " ".join(parts).format(**R)
    what, used, per, pers = sk["what"], sk["used"], sk["per"], sk["pers"]
    tk = "t1"
    if pause:
        tk = "act"
        p.step("act", lambda e: e["t1"] - e["p"], T, sk["act"], how="{t1} − {p}", show=False,
               alts=[_alt("exception", lambda e: e["t1"], "ignores that nothing was used during the first %s" % T.s(pz))])
    p.step("l1", lambda e: e["r1"] * e[tk], Q, "the %s%s" % (used, " in the first phase" if two else ""), how="{r1} × {%s}" % tk,
           tp=["At {r1} per %s over {%s} %s, the %s is {r}." % (per, tk, pers, used),
               "{%s} %s at {r1} per %s makes {r}." % (tk, pers, per)], alts=[_sw("operand", "t1", "t2")] if two else [])
    lk = "l1"
    if two:
        p.step("l2", lambda e: e["r2"] * e["t2"], Q, "the %s in the second phase" % used, how="{r2} × {t2}",
               tp=["{t2} %s at {r2} per %s makes {r}." % (pers, per)], alts=[_sw("operand", "t2", "t1"), _sw("operand", "r2", "r1")])
        p.step("tot", lambda e: e["l1"] + e["l2"], Q, "the total %s" % used, how="{l1} + {l2}")
        lk = "tot"
    p.step("rem", lambda e: e["S"] - e[lk], Q, "the %s left after that" % what, how="{S} − {%s}" % lk,
           labs=["the %s left after that" % what, "the %s remaining before the %s" % (what, sk["addn"])],
           tp=["Taking {%s} from {S} leaves {r}." % lk], alts=[_sw("operand", "S", "C")] if cap else [])
    p.step("mid", lambda e: e["rem"] + e["A"], Q, "the %s after the %s" % (what, sk["addn"]), how="{rem} + {A}",
           tp=["Adding the %s of {A} brings it to {r}." % sk["addn"]])
    if out:
        p.step("fin", lambda e: e["mid"] - e["B"], Q, "the %s at the end" % what, how="{mid} − {B}",
               tp=["Taking out {B} leaves {r}."])
    p.final = "the %s at the end" % what
    return p


