def _invoice(rng):
    sk = rng.choice(INV)
    p = Prob("invoice", sk["dom"])
    var = rng.choice(["disc", "tax", "exempt", "ship"])
    n = 2 if var in ("exempt", "ship") else rng.choice([2, 3])
    items = rng.sample(sk["items"], n)
    P = Fmt("n", suf="%")
    rows = []
    for i, it in enumerate(items, 1):
        q, pr = p.giv("q%d" % i, D(rng.randint(2, 48)), N, "the quantity of %s" % it), p.giv(
            "p%d" % i, _dec(rng, 1.05, 119.95, 2), M, "the unit price of %s" % it)
        rows.append((it, q, pr))
    form = rng.choice(["inline", "list", "table"])
    if form == "inline":
        lines = ": " + _and("%s %s at %s each" % (q, it, pr) for it, q, pr in rows) + "."
    elif form == "list":
        lines = ":\n" + "\n".join("- %s: %s at %s each" % (it, q, pr) for it, q, pr in rows) + "\n"
    else:
        lines = ":\n| item | quantity | unit price |\n" + "\n".join("| %s | %s | %s |" % r for r in rows) + "\n"
    pct = _dec(rng, 2, 24, 0) if rng.random() < 0.7 else _dec(rng, 2.5, 19.5, 1)
    if var in ("disc", "exempt"):
        R = p.giv("d", pct, P, "the discount rate")
        j = rng.randrange(n) + 1
        terms = (rng.choice(["A trade discount of %s%% applies to the subtotal.", "The supplier takes %s%% off the subtotal."]) % R
                 if var == "disc" else "A discount of %s%% applies, but it does not apply to the %s." % (R, items[j - 1]))
        ask = "What is the amount payable?"
    else:
        R = p.giv("tx", pct, P, "the tax rate")
        terms = rng.choice(["Sales tax of %s%% is added to the subtotal.", "Tax at %s%% applies to the subtotal."]) % R
        if var == "ship":
            terms = "Tax at %s%% applies to the goods. A flat delivery charge of %s is added afterwards and is not taxed." % (
                R, p.giv("sh", _dec(rng, 8, 95, 2), M, "the delivery charge"))
        ask = "What is the invoice total?"
    p.request = " ".join([sk["who"].format(org=rng.choice(ORGS)) + lines + ("" if form == "inline" else terms)] +
                         ([terms] if form == "inline" else []) + [rng.choice(ROUND), ask, rng.choice(ASK)])
    for i, it in enumerate(items, 1):
        o = i % n + 1
        p.step("L%d" % i, lambda e, i=i: e["q%d" % i] * e["p%d" % i], M, "the line total for the %s" % it, how="{q%d} × {p%d}" % (i, i),
               labs=["the line total for the %s" % it, "the cost of the %s" % it],
               alts=[_sw("operand", "q%d" % i, "q%d" % o), _sw("operand", "p%d" % i, "p%d" % o)])
    ks = ["L%d" % i for i in range(1, n + 1)]
    p.step("sub", lambda e: sum(e[k] for k in ks), M, "the subtotal", how=" + ".join("{%s}" % k for k in ks),
           tp=["Adding the lines, " + " + ".join("{%s}" % k for k in ks) + " = {r}."])
    if var in ("disc", "exempt"):
        base = "sub"
        if var == "exempt":
            base = "elig"
            p.step("elig", lambda e: e["sub"] - e["L%d" % j], M, "the amount the discount applies to", how="{sub} − {L%d}" % j, show=False,
                   alts=[_alt("exception", lambda e: e["sub"], "ignores that the %s get no discount" % items[j - 1])])
        p.step("disc", lambda e: _q(e[base] * e["d"] / 100), M, "the discount", how="{d}%% of {%s}" % base)
        p.step("net", lambda e: e["sub"] - e["disc"], M, "the amount payable", how="{sub} − {disc}",
               tp=["Taking {disc} off {sub} leaves {r}."])
        p.final = "the amount payable"
    else:
        if var == "ship":
            p.step("tax", lambda e: _q(e["sub"] * e["tx"] / 100), M, "the tax", how="{tx}% of {sub}", show=False,
                   alts=[_alt("exception", lambda e: _q((e["sub"] + e["sh"]) * e["tx"] / 100), "taxes the delivery charge, which is not taxed")])
            p.step("tot", lambda e: e["sub"] + e["tax"] + e["sh"], M, "the invoice total", how="{sub} + {tax} + {sh}")
        else:
            p.step("tax", lambda e: _q(e["sub"] * e["tx"] / 100), M, "the tax", how="{tx}% of {sub}")
            p.step("tot", lambda e: e["sub"] + e["tax"], M, "the invoice total", how="{sub} + {tax}",
                   tp=["Adding {tax} to {sub} gives {r}."])
        p.final = "the invoice total"
    return p


