def _cands(p: Prob, sty: dict, env: dict) -> Dict[str, list]:
    c: Dict[str, list] = {}
    n = len(p.steps)
    for k, st in enumerate(p.steps):
        key = st["key"]
        for w in p.f[key].slips(env[key]):
            c.setdefault("slip", []).append({"k": k, "ov": {k: w}, "w": w})
            if k < n - 1:
                c.setdefault("slip_iso", []).append({"k": k, "res": {k: w}, "w": w})
        for a in _ops(sty["tp"][k][1]):
            for w in p.f[a].slips(env[a]):
                c.setdefault("copy", []).append({"k": k, "loc": {k: {a: w}}, "a": a, "w": w})
                c.setdefault("copy_iso", []).append({"k": k, "disp": {k: {a: w}}, "a": a, "w": w})
        for alt in st["alts"]:
            if "swap" in alt:
                a, b = alt["swap"]
                c.setdefault(alt["t"], []).append({"k": k, "loc": {k: {a: env[b]}}, "alt": alt})
            else:
                c.setdefault(alt["t"], []).append({"k": k, "ov": {k: alt["fn"]}, "alt": alt})
    if sty["fin"]:
        last = p.steps[-1]["key"]
        for w in p.f[last].slips(env[last]):
            c.setdefault("final", []).append({"k": n, "final": w, "w": w})
    return c


def _apply(p: Prob, sty: dict, typ: str, c: dict, base, env: dict, allowed: set) -> Optional[dict]:
    """Render candidate ``c``; keep it only if every sentence keeps its length, something changed, and the first
    changed sentence holds a number that is neither in the request nor in the correct response."""
    c = dict(c)
    try:
        if "ov" in c or "loc" in c:
            c["env"] = _chain(p, c.get("ov"), c.get("loc"))
            if "loc" in c:
                c["disp"] = c["loc"]
        sents, fin = _render(p, sty, c)
    except (Inexact, ArithmeticError, ValueError, OverflowError):
        return None
    new, old = sents + [fin or ""], base[0] + [base[1] or ""]
    if [len(x) for x in new] != [len(x) for x in old]:
        return None
    diff = [i for i, (a, b) in enumerate(zip(new, old)) if a != b]
    if not diff or not (_toks(new[diff[0]]) - allowed):
        return None
    key = p.steps[min(c["k"], len(p.steps) - 1)]["key"]
    if typ == "copy" and c["env"][key] == env[key]:
        return None
    last = p.steps[-1]["key"]
    shown_final = c["final"] if c.get("final") is not None else (c.get("env") or env)[last]
    return {"type": typ, "k": c["k"], "sents": sents, "fin": fin, "why": _why(p, env, typ, c), "diff": diff,
            "final_wrong": shown_final != env[last]}


def _corrupt(p: Prob, sty: dict, base, rng, typ: str, min_k: int = 0) -> Optional[dict]:
    """One valid corruption of type ``typ`` (planted at step ``>= min_k``), or None if this problem / style has none."""
    env = _chain(p)
    cs = [c for c in _cands(p, sty, env).get(typ, []) if c["k"] >= min_k]
    allowed = _toks(p.request) | _toks(" ".join(base[0] + [base[1] or ""]))
    for st in p.steps:  # constants a correct response may state (a mean's divisor, a unit factor) are not "wrong" numbers
        if st["how"]:
            allowed |= _toks(st["how"].format(**{a: p.f[a].o(env[a]) for a in _ops(st["how"])}))
    rng.shuffle(cs)
    for c in cs[:80]:
        out = _apply(p, sty, typ, c, base, env, allowed)
        if out:
            return out
    return None


def _why(p: Prob, env: dict, typ: str, c: dict) -> str:
    fs = lambda key, v: p.f[key].s(v)  # noqa: E731
    n, last = len(p.steps), p.steps[-1]["key"]
    cf = fs(last, env[last])
    if typ == "final":
        return "The working is right and gives %s, but the stated final answer is %s." % (cf, fs(last, c["final"]))
    k = c["k"]
    st = p.steps[k]
    key, name = st["key"], p.nm[st["key"]]
    good = ((st["how"].format(**{a: p.f[a].o(env[a]) for a in _ops(st["how"])}) + " = ") if st["how"] else "") + fs(key, env[key])
    e2 = c.get("env") or env
    if typ in ("slip", "slip_iso"):
        head = "%s is wrong: %s, not %s." % (_cap(name), good, fs(key, c["w"]))
    elif typ in ("copy", "copy_iso"):
        a = c["a"]
        head = "The step for %s copies %s as %s instead of %s" % (name, p.nm[a], p.f[a].o(c["w"]), p.f[a].o(env[a]))
        if typ == "copy_iso":
            return head + "; the result shown is the correct one, so only the copied figure is wrong. The final answer %s is right, but the response is not fully correct." % cf
        head += ", so it gets %s instead of %s." % (fs(key, e2[key]), fs(key, env[key]))
    elif "swap" in c["alt"]:
        a, b = c["alt"]["swap"]
        head = "%s uses %s (%s) where %s (%s) belongs: %s, not %s." % (
            _cap(name), p.nm[b], p.f[a].o(env[b]), p.nm[a], p.f[a].o(env[a]), good, fs(key, e2[key]))
    else:
        head = "%s %s: %s, not %s." % (_cap(name), c["alt"]["why"], good, fs(key, e2[key]))
    if typ == "slip_iso":
        return head + " Later steps use the correct value, so the final answer %s stands, but the response is not fully correct." % cf
    if k < n - 1 and e2[last] != env[last]:
        return head + " The error carries forward: the final answer should be %s, not %s." % (cf, fs(last, e2[last]))
    return head


def _all_good(p: Prob) -> str:
    env = _chain(p)
    return "Every step checks out: %s." % "; ".join("%s %s" % (p.nm[s["key"]], p.f[s["key"]].s(env[s["key"]])) for s in p.steps)


