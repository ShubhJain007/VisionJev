class Inexact(Exception):
    """A value that cannot be written exactly in its format, or an exact rounding tie: resample / drop the candidate."""


def _q(x, dp=2):
    q = D(1).scaleb(-dp)
    r = x.quantize(q, ROUND_HALF_UP)
    if abs(x - r) * 2 == q:  # an exact tie: two readings of "round" would differ
        raise Inexact
    return r


def _dec(rng, lo, hi, dp=0):
    m = 10 ** dp
    return D(rng.randint(int(round(lo * m)), int(round(hi * m)))) / m


def _cap(s):
    return s[0].upper() + s[1:]


def _low(s):
    return s[0].lower() + s[1:]


def _and(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1]


def _person(rng):
    return "%s %s" % (rng.choice(FIRST), rng.choice(LAST))


class Fmt:
    """How a value is written: ``n`` natural decimal (trailing zeros stripped, up to 3 places), ``m`` money (2 places,
    thousands commas), ``i`` integer, ``d`` date, ``c`` clock time (minutes since midnight). ``o`` is the operand form
    (no unit suffix), ``s`` the result form. ``slips`` are the values one digit away (the digit changed by one)."""

    def __init__(self, kind="n", pre="", suf=""):
        self.kind, self.pre, self.suf = kind, pre, suf

    def bare(self, v) -> str:
        k = self.kind
        if k == "d":
            return v.strftime("%d %b %Y")
        if v < 0:
            raise Inexact
        if k == "c":
            if v != int(v) or v >= 1440:
                raise Inexact
            return "%02d:%02d" % divmod(int(v), 60)
        if k == "m":
            if v != v.quantize(D("0.01")):
                raise Inexact
            return format(v.quantize(D("0.01")), ",.2f")
        if k == "i":
            if v != v.to_integral_value():
                raise Inexact
            return "%d" % v
        if v != v.quantize(D("0.001")):
            raise Inexact
        t = format(v.quantize(D("0.001")), "f").rstrip("0").rstrip(".")
        return t or "0"

    def o(self, v) -> str:
        return self.pre + self.bare(v)

    def s(self, v) -> str:
        return self.pre + self.bare(v) + self.suf

    def parse(self, t: str):
        if self.kind == "d":
            return datetime.strptime(t, "%d %b %Y").date()
        if self.kind == "c":
            h, m = t.split(":")
            if int(h) > 23 or int(m) > 59:
                raise ValueError(t)
            return D(int(h) * 60 + int(m))
        return D(t.replace(",", ""))

    def slips(self, v) -> list:
        s = self.bare(v)
        idx = [i for i, ch in enumerate(s) if ch in DIG]
        numeric = self.kind not in ("d", "c")
        if self.kind == "d":
            idx = idx[:2]  # the day of the month
        nz = [i for i in idx if s[i] != "0"]
        last = (nz[-1] if nz else -1) if numeric else idx[-1]  # never turn a trailing zero into a digit (a lattice tell)
        out = []
        for i in idx:
            if i > last:
                continue
            for d in (-1, 1):
                nd = int(s[i]) + d
                if not 0 <= nd <= 9 or (numeric and i == 0 and nd == 0 and len(s) > 1 and s[1] != "."):
                    continue
                t = s[:i] + str(nd) + s[i + 1:]
                try:
                    w = self.parse(t)
                    if self.bare(w) == t:
                        out.append(w)
                except (ValueError, Inexact):
                    pass
        return out


class Prob:
    """One request and its chain: givens ``g``, formats ``f``, names ``nm`` (for rationales) and ordered ``steps``."""

    def __init__(self, kind, dom):
        self.kind, self.dom = kind, dom
        self.g, self.f, self.nm, self.steps = {}, {}, {}, []
        self.request, self.final = "", "the result"

    def giv(self, key, val, fmt, name) -> str:
        self.g[key], self.f[key], self.nm[key] = val, fmt, name
        return fmt.o(val)

    def step(self, key, fn, fmt, name, how=None, show=True, tp=(), alts=(), labs=()):
        """``how``: the expression (operand placeholders) for the rationale and, if ``show``, for explicit templates;
        ``tp``: extra templates of this step (result last); ``alts``: planted mistakes, ``{"t", "swap": (a, b)}`` =
        computed with given ``b`` in place of ``a``, or ``{"t", "fn", "why"}``."""
        self.f[key], self.nm[key] = fmt, name
        self.steps.append({"key": key, "fn": fn, "how": how, "show": bool(show and how), "tp": list(tp), "alts": list(alts),
                           "labs": list(labs) or [name]})


def _chain(p: Prob, ov=None, loc=None) -> dict:
    """Values of every step. ``ov[k]`` replaces step k's result (a value, or a function of the environment);
    ``loc[k]`` replaces operands for step k only. Later steps are recomputed, so an error carries forward."""
    env = dict(p.g)
    for k, st in enumerate(p.steps):
        e = dict(env, **loc[k]) if loc and k in loc else env
        o = ov.get(k) if ov else None
        env[st["key"]] = o(e) if callable(o) else (o if o is not None else st["fn"](e))
    return env


