def _avg_readings(rng):
    dom, tpl, ttpl, u, dp, (lo, hi), tname = rng.choice(AVG_SK)
    p = Prob("avg_readings", dom)
    F = M if u == "$" else Fmt("n", suf=" " + u)
    q = D(1).scaleb(-dp)
    k = rng.choice([4, 5])
    exc = rng.choice(AVG_EXC) if rng.random() < 0.55 else None
    mean = _dec(rng, lo, hi, dp)
    spread = float(mean) * 0.06 + float(q) * 4
    xs = [mean + _dec(rng, -spread, spread, dp) for _ in range(k - 1)]
    xs.append(k * mean - sum(xs))
    if abs(xs[-1] - mean) > D(str(spread)) * 2 or len(set(xs)) < k:
        return None
    if exc:
        up = exc[0] in ("highest", "largest")
        edge = max(xs) if up else min(xs)
        step = k * q
        x = ((edge / step).to_integral_value() + (rng.randint(1, 4) if up else -rng.randint(1, 4))) * step
        if (up and x <= max(xs)) or (not up and (x >= min(xs) or x <= 0)):
            return None
        xs.insert(rng.randrange(k + 1), x)
    else:
        rng.shuffle(xs)
    keys = ["x%d" % (i + 1) for i in range(len(xs))]
    shown = [p.giv(key, v, F, "reading %d" % (i + 1)) for i, (key, v) in enumerate(zip(keys, xs))]
    gap = _dec(rng, 1, 12, 0) * q * rng.choice([1, 2, 5])
    T = p.giv("T", mean - gap, F, tname)
    p.request = " ".join([tpl.format(who=_person(rng), xs=_and(shown))] + ([exc[1]] if exc else []) + [
        ttpl.format(T=T), "By how much does the mean of the values that count exceed that figure?" if exc else "By how much does the mean exceed that figure?",
        rng.choice(ASK)])
    if exc:
        kept = [key for key in keys if p.g[key] != x]
        p.step("sum", lambda e: sum(e[a] for a in kept), F, "the sum of the values that count", how=" + ".join("{%s}" % a for a in kept), show=False,
               alts=[_alt("exception", lambda e: sum(e[a] for a in keys), "includes the %s value, which must be left out" % exc[0])])
    else:
        p.step("sum", lambda e: sum(e[a] for a in keys), F, "the sum of the values", how=" + ".join("{%s}" % a for a in keys))
    p.step("mean", lambda e: e["sum"] / k, F, "the mean", how="{sum} ÷ %d" % k, labs=["the mean", "the average"])
    p.step("gap", lambda e: e["mean"] - e["T"], F, "the amount by which the mean exceeds the figure", how="{mean} − {T}",
           labs=["the excess over " + tname, "the gap above " + tname])
    p.final = "the excess"
    return p


