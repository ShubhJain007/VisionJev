def _clock(m: int) -> str:
    return "%02d:%02d" % divmod(m, 60)


def adequacy_item(rng, n_req: int, viol: Optional[int]) -> dict:
    """A request with ``n_req`` explicit requirements and a response meeting all of them, or all but number ``viol``.
    Response features exist whether or not a requirement asks for them, and the word limit is set AFTER the response
    is written, so the response text does not depend on which requirement is broken (except in that one feature)."""
    d = rng.choice(ADQ)
    types = rng.sample(RTYPES, n_req)
    bad = types[viol] if viol is not None else None
    has = lambda t: t in types  # noqa: E731
    me, other = _person(rng), _person(rng)
    while other.split()[0] == me.split()[0]:
        other = _person(rng)
    idv = _ref(rng, d["idpre"])
    id2 = _ref(rng, d["idpre"])
    day = date(2026, rng.randint(1, 12), rng.randint(2, 27))
    day2 = day + timedelta(days=rng.choice([-14, -7, 7, 14]))
    amounts = [_dec(rng, 18, 640, 2) for _ in range(3)]
    total = sum(amounts)
    sup, team, team2 = rng.choice(SUPPLIERS), *rng.sample(d["teams"], 2)
    sent = rng.choice(SENTS)
    ev, note = {}, {}  # evidence per requirement (rationale), wording of the requirement
    # ---- list --------------------------------------------------------------------------------------------------------
    K, form = rng.randint(3, 6), rng.choice(["max", "min", "eq"])
    if has("items"):
        ok_n = {"max": [K - 1, K], "min": [K, K + 1], "eq": [K]}[form]
        bad_n = {"max": [K + 1], "min": [K - 1], "eq": [K - 1, K + 1]}[form]
        n_items = rng.choice(bad_n if bad == "items" else ok_n)
        words = {"max": "no more than", "min": "at least", "eq": "exactly"}[form]
        ev["items"] = ("it lists %d %s, but the request says %s %d" if bad == "items" else "%d %s listed (%s %d)") % (n_items, d["noun"], words, K)
        note["items"] = rng.choice(REQ_T["items_" + form]).format(v=K, noun=d["noun"])
    else:
        n_items = rng.randint(3, 6)
    items = rng.sample(d["items"], n_items)
    numbered = (bad != "numbered") if has("numbered") else rng.random() < 0.5
    mark = None if numbered else rng.choice(["- ", "• "])
    if has("numbered"):
        ev["numbered"] = "the %s are bulleted, not numbered" % d["noun"] if bad == "numbered" else "the %s are numbered" % d["noun"]
        note["numbered"] = rng.choice(REQ_T["numbered"]).format(noun=d["noun"])
    lines = []
    # ---- subject, greeting ----------------------------------------------------------------------------------------------
    topic = rng.choice(d["topic"])
    if has("subject"):
        if bad == "subject":
            if rng.random() < 0.7:
                lines.append("%s %s" % (rng.choice(["Re:", "Topic:", "About:"]), topic))
        else:
            lines.append("Subject: " + topic)
        ev["subject"] = "the first line does not start with 'Subject:'" if bad == "subject" else "it opens with a Subject line"
        note["subject"] = rng.choice(REQ_T["subject"])
    elif rng.random() < 0.55:
        lines.append("%s %s" % (rng.choice(["Subject:", "Subject:", "Re:", "Topic:", "About:"]), topic))
    greet = other if bad == "addressee" else me
    lines.append(rng.choice(["Hi %s,", "Hello %s,"]) % greet.split()[0] if rng.random() < 0.6 else "Dear %s," % greet)
    if has("addressee"):
        ev["addressee"] = "it greets %s instead of %s" % (other, me) if bad == "addressee" else "addressed to %s" % me
        note["addressee"] = rng.choice(REQ_T["addressee"]).format(v=me)
    # ---- opening paragraph: id and date ---------------------------------------------------------------------------------
    para = []
    if has("id") or rng.random() < 0.5:
        shown = (id2 if rng.random() < 0.5 and id2 != idv else _swap_digits(rng, idv)) if bad == "id" else idv
        para.append(rng.choice(["This is logged under %s %s.", "For reference, this concerns %s %s.", "I have updated %s %s with these notes."]) % (d["idkind"], shown))
        if has("id"):
            ev["id"] = "it quotes %s instead of %s" % (shown, idv) if bad == "id" else "%s is quoted" % idv
            note["id"] = rng.choice(REQ_T["id"]).format(v=idv, idkind=d["idkind"])
    if has("date") or rng.random() < 0.5:
        shown = (day2 if rng.random() < 0.5 else day + timedelta(days=rng.choice([-1, 1]))) if bad == "date" else day
        para.append(rng.choice(["The %s is set for %s.", "We have the %s down for %s."]) % (d["event"], _long_date(shown)))
        if has("date"):
            ev["date"] = "it gives %s instead of %s" % (_long_date(shown), _long_date(day)) if bad == "date" else "%s is mentioned" % _long_date(day)
            note["date"] = rng.choice(REQ_T["date"]).format(v=_long_date(day), event=d["event"])
    rng.shuffle(para)
    lines.append(" ".join([rng.choice(d["open"])] + para))
    lines.append(rng.choice(d["intro"]))
    lines += ["%s%s" % (("%d. " % (i + 1)) if numbered else mark, it) for i, it in enumerate(items)]
    # ---- closing paragraph: total, call time, supplier, fixed sentence, fillers -----------------------------------------
    para = rng.sample(d["fill"], rng.randint(1, 4))
    if has("total") or rng.random() < 0.3:
        wrong = rng.choice(M.slips(total) + [total - rng.choice(amounts)])
        shown = wrong if bad == "total" else total
        para.append(rng.choice(["The charges come to %s in total.", "Altogether the charges are %s."]) % M.s(shown))
        if has("total"):
            ev["total"] = "it states %s, but the charges add up to %s" % (M.s(shown), M.s(total)) if bad == "total" else "the total %s is right" % M.s(total)
            note["total"] = rng.choice(REQ_T["total"])
    t1 = rng.randint(16, 30) * 30
    t2 = t1 + rng.choice([90, 120, 150, 180])
    if has("time") or rng.random() < 0.3:
        inside = t1 + 15 * rng.randint(1, (t2 - t1) // 15 - 1)
        outside = rng.choice([t1 - 15 * rng.randint(1, 3), t2 + 15 * rng.randint(1, 3)])
        shown = outside if bad == "time" else inside
        para.append(rng.choice(["I can call you at %s to go through it.", "Would a call at %s suit you?"]) % _clock(shown))
        if has("time"):
            ev["time"] = ("%s is outside the window %s to %s" if bad == "time" else "%s is inside the window %s to %s") % (_clock(shown), _clock(t1), _clock(t2))
            note["time"] = rng.choice(REQ_T["time"]).format(v=_clock(t1), v2=_clock(t2))
    named = (bad == "forbid") if has("forbid") else rng.random() < 0.5
    para.append(rng.choice(["%s will handle the %s.", "%s is looking after the %s."]) % (sup if named else "Our " + d["supkind"], d["thing"]))
    if has("forbid"):
        ev["forbid"] = "it names %s" % sup if bad == "forbid" else "%s is not named" % sup
        note["forbid"] = rng.choice(REQ_T["forbid"]).format(v=sup, supkind=d["supkind"])
    rng.shuffle(para)
    if has("sentence") or rng.random() < 0.3:
        para.append(sent[1] if (bad == "sentence" if has("sentence") else rng.random() < 0.5) else sent[0])
        if has("sentence"):
            ev["sentence"] = "the required sentence is reworded" if bad == "sentence" else "the required sentence appears word for word"
            note["sentence"] = rng.choice(REQ_T["sentence"]).format(v=sent[0])
    lines.append(" ".join(para))
    sign = team2 if bad == "signoff" else team
    lines += ["— " + sign] if rng.random() < 0.3 else [rng.choice(["Regards,", "Thanks,", "Kind regards,"]), sign]
    if has("signoff"):
        ev["signoff"] = "it signs off as %s, not %s" % (team2, team) if bad == "signoff" else "signed off as %s" % team
        note["signoff"] = rng.choice(REQ_T["signoff"]).format(v=team)
    response = "\n".join(lines)
    # ---- word limit: set from the finished response -----------------------------------------------------------------------
    if has("words"):
        n_words, wform, margin = len(response.split()), rng.choice(["max", "min"]), rng.randint(10, 24)
        over = (wform == "max") == (bad == "words")  # the limit must sit BELOW the length when (max, broken) or (min, met)
        W = (n_words - margin) // 5 * 5 if over else -(-(n_words + margin) // 5) * 5
        words = "at most" if wform == "max" else "at least"
        ev["words"] = ("it has %d words, but the request says %s %d" if bad == "words" else "%d words (%s %d)") % (n_words, words, W)
        note["words"] = rng.choice(REQ_T["words_" + wform]).format(v=W)
    bg = rng.choice(BG).format(me=me, other=other, role=d["role"], idkind=d["idkind"], id=idv, id2=id2, event=d["event"], dt=_long_date(day),
                               dt2=_long_date(day2), a1=M.s(amounts[0]), a2=M.s(amounts[1]), a3=M.s(amounts[2]), c1=d["charges"][0],
                               c2=d["charges"][1], c3=d["charges"][2], supkind=d["supkind"], sup=sup)
    style = rng.choice(["num", "alpha", "dash"])
    reqs = [note[t] for t in types]
    if style == "num":
        rl = "Requirements:\n" + "\n".join("%d. %s" % (i + 1, r) for i, r in enumerate(reqs))
    elif style == "alpha":
        rl = "Requirements: " + " ".join("(%s) %s" % ("abcdef"[i], r) for i, r in enumerate(reqs))
    else:
        rl = "The message must meet all of these:\n" + "\n".join("- " + r for r in reqs)
    request = "%s %s\n%s" % (rng.choice(d["ask"]), bg, rl)
    if bad:
        why = "One requirement is not met: %s. The other %d are met." % (ev[bad], n_req - 1)
    else:
        why = "Every requirement is met: %s." % "; ".join(ev[t] for t in types)
    return {"request": request, "response": response, "types": types, "bad": bad, "rationale": why, "kind": "%s:%s" % (d["dom"], bad or "ok")}


def judge_adequacy(rng, n: int = 10700) -> Iterator[ts.Row]:
    rng = random.Random("judge-adequacy")
    for i in range(n):
        n_req = rng.randint(3, 6)
        choice = rng.random() < 0.5
        met = rng.random() < (1 / (n_req + 1) if choice else 0.5)  # choice: "all met" is gold as often as any other option
        it = adequacy_item(rng, n_req, None if met else rng.randrange(n_req))
        if choice:
            v = rng.randrange(2)
            opts = [RLAB[t][v] for t in it["types"]] + [RLAB[None][v]]
            q, lab = ts._fixed_choice(rng.choice(ADQ_W), opts, len(opts) - 1 if met else it["types"].index(it["bad"]), rng)
        else:
            q, lab = {"type": "noul", "instructions": rng.choice(ADQ_Q), "criteria": rng.choice(ADQ_C)}, int(met)
        yield (_split("judge-adequacy-%d" % i), _state(rng, it["request"], [it["response"]]), q, lab, None,
               {"rationale": it["rationale"], "kind": it["kind"]})


