def _state(rng, request: str, responses: List[str], rubric: Optional[str] = None) -> str:
    """{request, response[, rubric]} or {request, response_A, response_B}: JSON or labelled prose, four key namings."""
    kq, kr, kb = rng.choice(NAMES)
    items = [(kq, request)]
    items += [(kr, responses[0])] if len(responses) == 1 else [("%s_%s" % (kr, x), r) for x, r in zip("AB", responses)]
    if rubric:
        items.insert(rng.choice([0, len(items)]), (kb, rubric))
    if rng.random() < 0.5:
        return json.dumps(dict(items), ensure_ascii=False)
    return "\n\n".join("%s: %s" % (_cap(k.replace("_", " ")), v) for k, v in items)


