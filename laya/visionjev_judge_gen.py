TOK = re.compile(r"\d{2} [A-Z][a-z]{2} \d{4}|\d{1,2}:\d{2}|\d+(?:,\d{3})*(?:\.\d+)?")


def _toks(text: str) -> set:
    return set(TOK.findall(text))


def _ops(t: str) -> List[str]:
    return [f for _, f, _, _ in string.Formatter().parse(t) if f and f not in ("r", "lab", "Lab")]


def _style(p: Prob, rng, final: Optional[bool] = None) -> dict:
    """Templates, connectives and layout of a response: chosen BEFORE and independently of any corruption."""
    tp = []
    for k, st in enumerate(p.steps):
        if st["tp"] and rng.random() < (0.45 if st["show"] else 0.65):
            t = rng.choice(st["tp"])
        elif st["show"] and rng.random() < 0.72:
            t = rng.choice(EXP).replace("{how}", st["how"])
        else:
            t = rng.choice(IMP)
        tp.append(("" if k == 0 else rng.choice(CONN), t, rng.choice(st["labs"])))
    fin = rng.choice(FINAL) if (rng.random() < 0.6 if final is None else final) else None
    return {"tp": tp, "fin": fin, "layout": rng.choice(LAYOUTS)}


def _sent(p: Prob, k: int, sty: dict, vals: dict, r) -> str:
    conn, t, lab = sty["tp"][k]
    m = {a: p.f[a].o(vals[a]) for a in _ops(t)}
    m.update(r=p.f[p.steps[k]["key"]].s(r), lab=lab, Lab=lab if conn else _cap(lab))
    s = t.format(**m)
    return conn + (s if t.startswith("{") else _low(s)) if conn else s


def _render(p: Prob, sty: dict, cor: Optional[dict] = None):
    """-> (step sentences, final line or None). ``cor``: ``env`` (values shown), ``disp[k]`` (operands shown in step
    k only), ``res[k]`` (result shown in step k only), ``final`` (value shown on the final line only)."""
    cor = cor or {}
    shown = cor.get("env") or _chain(p)
    out = []
    for k, st in enumerate(p.steps):
        vals = dict(shown, **cor.get("disp", {}).get(k, {}))
        out.append(_sent(p, k, sty, vals, cor.get("res", {}).get(k, shown[st["key"]])))
    fin = None
    if sty["fin"]:
        last = p.steps[-1]["key"]
        v = cor["final"] if cor.get("final") is not None else shown[last]
        fin = sty["fin"].format(r=p.f[last].s(v), what=p.final, What=_cap(p.final))
    return out, fin


def _join(sents: List[str], fin: Optional[str], layout: str) -> str:
    if layout == "num":
        sents = ["%d. %s" % (i + 1, s) for i, s in enumerate(sents)]
    elif layout == "step":
        sents = ["Step %d: %s" % (i + 1, s) for i, s in enumerate(sents)]
    return (" " if layout == "para" else "\n").join(sents + ([fin] if fin else []))


