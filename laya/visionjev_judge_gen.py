EL_LEAD = ["Also:", "In the answer:", "Presentation:"]
FINAL_TYPES = ("slip", "copy", "operand", "exception", "unit", "offby1", "final")


def _long_date(d: date) -> str:
    return "%d %s" % (d.day, d.strftime("%B %Y"))


def _ref(rng, pre=None) -> str:
    return "%s-%d" % (pre or rng.choice(["QX", "RF", "JN", "WK", "LT"]), rng.randint(10000, 99999))


def _swap_digits(rng, s: str) -> str:
    """The same id with two neighbouring digits swapped (or, if all digits are equal, one digit changed)."""
    idx = [i for i in range(len(s) - 1) if s[i] in DIG and s[i + 1] in DIG and s[i] != s[i + 1]]
    if not idx:
        return s[:-1] + str((int(s[-1]) + 1) % 10)
    i = rng.choice(idx)
    return s[:i] + s[i + 1] + s[i] + s[i + 2:]


def rubric_item(rng, target: int) -> dict:
    """A rubric row whose level is ``target`` (rejection sampling over rubric parameters and defect sets)."""
    off = target == 0 and rng.random() < 0.5  # half of the level-0 rows are off-task, half reach 0 through the rubric
    while True:
        text, level, explain = make_rubric(rng)
        n_req = rng.choice([1, 2])
        num = rng.choice([None, "mid", "final"])
        miss = rng.randint(0, n_req)
        if level(num, miss, off) == target:
            break
    w = worked(rng, types=ISO if num == "mid" else FINAL_TYPES, min_k=1, final=True)
    if num == "final" and not w["bad"]["final_wrong"]:
        return rubric_item(rng, target)
    p = w["p"]
    body = w["bad_text"] if num else w["good_text"]
    if off:
        env = _chain(p)
        mine = {p.f[s["key"]].bare(env[s["key"]]) for s in p.steps}
        while True:
            o = worked(rng, final=True)
            if o["p"].kind != p.kind and not (_toks(o["good_text"]) & mine):
                break
        body = o["good_text"]
    who, other = _person(rng), _person(rng)
    while other.split()[0] == who.split()[0]:
        other = _person(rng)
    day = _day0(rng)
    vals = {"addressee": who, "reference": _ref(rng), "date": _long_date(day)}
    req = rng.sample(sorted(vals), n_req)
    bad = set(rng.sample(req, miss))
    head, reqs = [], []
    for el in ("addressee", "reference", "date"):
        v = vals[el]
        if el in req:
            reqs.append(rng.choice(EL_REQ[el]).format(v=v))
        elif rng.random() < 0.7:
            continue  # an element nobody asked for is usually absent
        if el in bad:
            if rng.random() < 0.5:
                continue  # missing
            v = (other if el == "addressee" else _swap_digits(rng, v) if el == "reference" else
                 _long_date(day + timedelta(days=rng.choice([-1, 1, 7]))))  # present but wrong
        t = rng.choice(EL_OUT[el])
        head.append(t.format(v=v.split()[0] if el == "addressee" and t.startswith("Hi") else v))
    rng.shuffle(reqs)
    request = p.request + "\n\n" + rng.choice(EL_LEAD) + " " + " ".join(reqs)
    response = ("\n".join(head) + "\n\n" if head else "") + body
    if off:
        why = "The response answers a different task, so it scores 0."
    else:
        why = (w["bad"]["why"] if num else "All figures are right.") + " " + (
            "Required element missing or wrong: %s." % _and("the " + e for e in sorted(bad)) if bad else "Every required element is present.") + (
            " Rubric: %s, so the score is %d." % (explain(num, miss), target))
    tag = "off" if off else "+".join(([num] if num else []) + (["miss%d" % miss] if miss else [])) or "ok"
    return {"request": request, "response": response, "rubric": text, "label": target, "rationale": why, "kind": "%s:%s" % (p.kind, tag)}


def judge_rubric_cap(rng, n: int = 10700) -> Iterator[ts.Row]:
    rng = random.Random("judge-rubric-cap")
