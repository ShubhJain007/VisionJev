def make_rubric(rng):
    """-> (text, level(num, miss, off), explain(num, miss)). ``num``: None / 'mid' / 'final'; ``miss``: elements missing or wrong."""
    fam = rng.choice(["cap", "deduct", "ladder"])
    if fam == "cap":
        cf, cm, ce, extra = rng.choice([1, 2]), rng.choice([2, 3]), rng.choice([2, 3]), rng.random() < 0.5
        text = rng.choice(CAP_T).format(cf=cf, cm=cm, ce=ce, x=CAP_X if extra else "")

        def parts(num, miss):
            return ([("final answer", cf)] if num == "final" else [("working", cm)] if num == "mid" else []) + ([("element", ce)] if miss else [])

        def level(num, miss, off):
            caps = [c for _, c in parts(num, miss)]
            return 0 if off else max(0, min([4] + caps) - (1 if extra and len(caps) == 2 else 0))

        def explain(num, miss):
            ps = parts(num, miss)
            return ("no cap applies" if not ps else "caps: " + ", ".join("%s %d" % x for x in ps)) + (
                ", minus one because both kinds apply" if extra and len(ps) == 2 else "")
    elif fam == "deduct":
        x, y, z = rng.choice([2, 3]), rng.choice([1, 2]), rng.choice([1, 2])
        text = rng.choice(DED_T).format(x=x, y=y, z=z)

        def level(num, miss, off):
            return 0 if off else max(0, 4 - (x if num == "final" else y if num == "mid" else 0) - z * miss)

        def explain(num, miss):
            return "4" + (" − %d (final answer)" % x if num == "final" else " − %d (working)" % y if num == "mid" else "") + (
                " − %d × %d (elements)" % (z, miss) if miss else "") + ", floor 0"
    else:
        e1, m, f = rng.choice([3, 2]), rng.choice([3, 2]), rng.choice([1, 2])
        e2 = e1 - 1
        text = rng.choice(LAD_T).format(e1=e1, e2=e2, m=m, f=f)

        def level(num, miss, off):
            return 0 if off else min([4] + ([f] if num == "final" else [m] if num == "mid" else []) + ([e1] if miss == 1 else [e2] if miss >= 2 else []))

        def explain(num, miss):
            return "lowest applicable level"
    return text, level, explain


EL_REQ = {"addressee": ["Address the answer to {v}.", "Open by greeting {v} by name."],
          "reference": ["Quote reference {v}.", "Cite reference {v} in the answer."],
          "date": ["Date the answer {v}.", "Put the date {v} on the answer."]}
