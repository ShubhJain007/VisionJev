def _split(key: str, pct: int = 10) -> str:
    return "val" if int(hashlib.md5(key.encode()).hexdigest(), 16) % 100 < pct else "train"


def _parse(v):
    return ast.literal_eval(v) if isinstance(v, str) else v


# ---- commonsense / reasoning -----------------------------------------------------------------------------------------


def qasc_choice(rng) -> Iterator[ts.Row]:
    for hub, split in (("train", "train"), ("validation", "val")):
        for ex in ts._ds("allenai/qasc", split=hub):
            ch = _parse(ex["choices"])
            if ex["answerKey"] not in ch["label"]:
                continue
            q, lab = ts._fixed_choice(ex["question"], list(ch["text"]), ch["label"].index(ex["answerKey"]), rng)
            yield split, None, q, lab, None


def quartz_choice(rng) -> Iterator[ts.Row]:
    for hub, split in (("train", "train"), ("validation", "val"), ("test", "val")):
        for ex in ts._ds("allenai/quartz", split=hub):
            ch = _parse(ex["choices"])
            if ex["answerKey"] not in ch["label"]:
                continue
            q, lab = ts._fixed_choice(ex["question"], list(ch["text"]), ch["label"].index(ex["answerKey"]), rng)
            yield split, json.dumps({"background": ex["para"]}), q, lab, None


def ropes_choice(rng) -> Iterator[ts.Row]:
    for hub, split in (("train", "train"), ("validation", "val")):
        rows = list(ts._ds("allenai/ropes", split=hub))
        by_sit = defaultdict(set)
        for ex in rows:
            for a in _parse(ex["answers"])["text"]:
                by_sit[ex["situation"]].add(a.strip())
        for ex in rows:
            gold = _parse(ex["answers"])["text"][0].strip()
            others = sorted(by_sit[ex["situation"]] - {gold})
            if not others or len(gold) > 80:
                continue
            opts = [gold] + rng.sample(others, min(3, len(others)))
            q, lab = ts._fixed_choice(ex["question"], opts, 0, rng)
            state = {"background": ex["background"][:1500], "situation": ex["situation"][:1200]}
            yield split, json.dumps(state), q, lab, None


def strategyqa(rng) -> Iterator[ts.Row]:
    for hub in ("train", "test"):
        for ex in ts._ds("ChilleD/StrategyQA", split=hub):
            yield _split(ex["qid"], 12), None, ts._noul(ex["question"]), int(str(ex["answer"]) in ("True", "true", "1")), None


def winogrande(rng) -> Iterator[ts.Row]:
    for hub, split in (("train", "train"), ("validation", "val")):
        for ex in ts._ds("allenai/winogrande", "winogrande_xl", split=hub):
            if ex["answer"] not in ("1", "2"):
                continue
            q, lab = ts._fixed_choice("Who or what does the blank (_) refer to?", [ex["option1"], ex["option2"]],
                                      int(ex["answer"]) - 1, rng)
            yield split, json.dumps({"sentence": ex["sentence"]}), q, lab, None


# ---- multilingual reading --------------------------------------------------------------------------------------------


def _passages(ex):
    doc = ex["document_plaintext"].encode("utf-8")
    c = _parse(ex["passage_answer_candidates"])
    return [doc[s:e].decode("utf-8", "ignore").strip() for s, e in zip(c["plaintext_start_byte"], c["plaintext_end_byte"])]


def tydiqa_answerable(rng) -> Iterator[ts.Row]:
    for hub, split in (("train", "train"), ("validation", "val")):
        pool = []  # passages usable as exact negatives: from other documents
        for i, ex in enumerate(ts._ds("google-research-datasets/tydiqa", "primary_task", split=hub, streaming=True)):
            if i >= 60000:
                break
            ps = [p for p in _passages(ex) if 80 <= len(p) <= 1500]
            idx = [k for k in _parse(ex["annotations"])["passage_answer_candidate_index"] if k >= 0]
            allp = _passages(ex)
            if idx and 80 <= len(allp[idx[0]]) <= 1500:
                yield split, json.dumps({"question": ex["question_text"], "passage": allp[idx[0]]}, ensure_ascii=False), \
                    ts._noul("Does this passage answer the question?"), 1, None
                if pool:
                    other = rng.choice(pool)
                    if other[0] != ex["document_title"]:
                        yield split, json.dumps({"question": ex["question_text"], "passage": other[1]}, ensure_ascii=False), \
                            ts._noul("Does this passage answer the question?"), 0, None
            if ps:
                pool.append((ex["document_title"], rng.choice(ps)))
                if len(pool) > 2000:
                    pool.pop(rng.randrange(len(pool)))


# ---- math -----------------------------------------------------------------------------------------------------------


def _num(s) -> Optional[float]:
    try:
        return float(str(s).replace(",", "").strip())
    except ValueError:
        return None


def _fmt(x: float) -> str:
    return str(int(round(x))) if abs(x - round(x)) < 1e-9 else ("%.4f" % x).rstrip("0").rstrip(".")


def _numeric_choice(ins: str, true: float, candidates: List[float], rng, k: int = 4):
    """Gold + up to k-1 distinct distractors, rank-uniform around the true value (no median tell)."""
    cands = []
    for c in candidates + [true + d for d in (1, -1, 2, -2, 10, -10)] + [true * f for f in (2, 0.5, 10)]:
        if c is not None and abs(c - true) > 1e-9 and c >= 0 and _fmt(c) not in {_fmt(x) for x in cands} \
                and _fmt(c) != _fmt(true):
            cands.append(c)
    below = [c for c in cands if c < true]
    above = [c for c in cands if c > true]
    n = min(k - 1, len(below) + len(above))
    if n < 2:
        return None
    feasible = [r for r in range(n + 1) if r <= len(below) and n - r <= len(above)]
    r = rng.choice(feasible)
    opts = [true] + rng.sample(below, r) + rng.sample(above, n - r)
    opts = [_fmt(x) for x in opts]
    return ts._fixed_choice(ins, opts, 0, rng)


def gsm8k_choice(rng) -> Iterator[ts.Row]:
    for hub, split in (("train", "train"), ("test", "val")):
        for ex in ts._ds("openai/gsm8k", "main", split=hub):
            true = _num(ex["answer"].split("####")[-1])
            if true is None:
                continue
            inter = [_num(m) for m in re.findall(r"<<[^=]*=([-\d.,]+)>>", ex["answer"])]
            got = _numeric_choice(ex["question"], true, [x for x in inter if x is not None], rng)
            if got:
                yield split, None, got[0], got[1], None


def svamp_choice(rng) -> Iterator[ts.Row]:
    for hub in ("train", "test"):
        for ex in ts._ds("ChilleD/SVAMP", split=hub):
            true = _num(ex["Answer"])
            nums = [_num(x) for x in re.findall(r"[\d.]+", ex["Equation"])]
            nums = [x for x in nums if x is not None]
            cand = []
            if len(nums) >= 2:
                a, b = nums[0], nums[1]
                cand = [a + b, abs(a - b), a * b] + ([a / b] if b else [])
            got = _numeric_choice("%s %s" % (ex["Body"], ex["Question"]), true, cand, rng) if true is not None else None
            if got:
                yield _split(ex["ID"], 15), None, got[0], got[1], None


def _boxed(sol: str) -> Optional[str]:
    i = sol.rfind("\\boxed{")
    if i < 0:
        return None
    depth, j = 0, i + 7
    for k in range(j, len(sol)):
        if sol[k] == "{":
            depth += 1
        elif sol[k] == "}":
            if depth == 0:
                return sol[j:k]
            depth -= 1
    return None


MATH_TYPES = ["algebra", "counting_and_probability", "geometry", "intermediate_algebra", "number_theory", "prealgebra",
              "precalculus"]


def math_choice(rng) -> Iterator[ts.Row]:
    for t in MATH_TYPES:
        for hub, split in (("train", "train"), ("test", "val")):
            for ex in ts._ds("EleutherAI/hendrycks_math", t, split=hub):
                ans = _boxed(ex["solution"])
                true = _num(ans) if ans else None
                if true is None or len(ex["problem"]) > 1500:
                    continue
                nums = [_num(x) for x in re.findall(r"(?<![\w.])\d+(?:\.\d+)?", ex["solution"])]
                got = _numeric_choice(ex["problem"], true, [x for x in nums if x is not None], rng)
                if got:
                    yield split, None, got[0], got[1], None


def numina_choice(rng) -> Iterator[ts.Row]:
    for i, ex in enumerate(ts._ds("AI-MO/NuminaMath-1.5", split="train", streaming=True)):
        if i >= 400000:
            break
        if str(ex.get("synthetic")) == "True" or str(ex.get("problem_is_valid")) != "Yes" or len(ex["problem"]) > 1500:
            continue
        true = _num(ex.get("answer"))
        if true is None:
            continue
        nums = [_num(x) for x in re.findall(r"(?<![\w.])\d+(?:\.\d+)?", ex.get("solution") or "")]
        got = _numeric_choice(ex["problem"], true, [x for x in nums if x is not None], rng)
        if got:
            yield _split(ex["problem"][:200]), None, got[0], got[1], None


