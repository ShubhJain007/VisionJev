WIKISQL_URL = "https://github.com/salesforce/WikiSQL/raw/master/data.tar.bz2"
AGG = ["", "MAX", "MIN", "COUNT", "SUM", "AVG"]
COND = ["=", ">", "<"]


def _wikisql_split(split):
    import os
    import tarfile
    import urllib.request

    from .visionjev_data import RAW_ROOT

    raw = os.path.join(RAW_ROOT, "wikisql", "data.tar.bz2")
    if not os.path.exists(raw):
        os.makedirs(os.path.dirname(raw), exist_ok=True)
        urllib.request.urlretrieve(WIKISQL_URL, raw + ".tmp")
        os.rename(raw + ".tmp", raw)
    with tarfile.open(raw) as tar:
        q = [json.loads(l) for l in tar.extractfile("data/%s.jsonl" % split)]
        tables = {t["id"]: t for t in map(json.loads, tar.extractfile("data/%s.tables.jsonl" % split))}
    return q, tables


def _sql_text(sql, header):
    col = lambda i: '"%s"' % header[i].replace('"', "'")  # noqa: E731
    sel = col(sql["sel"]) if not sql["agg"] else "%s(%s)" % (AGG[sql["agg"]], col(sql["sel"]))
    s = "SELECT %s FROM t" % sel
    if sql["conds"]:
        s += " WHERE " + " AND ".join("%s %s %s" % (col(c), COND[o], json.dumps(v) if isinstance(v, str) else v)
                                      for c, o, v in sql["conds"])
    return s


def _run_sql(sql, table):
    import sqlite3

    db = sqlite3.connect(":memory:")
    n = len(table["header"])
    db.execute("CREATE TABLE t (%s)" % ", ".join('c%d %s' % (i, "REAL" if table["types"][i] == "real" else "TEXT")
                                                   for i in range(n)))
    db.executemany("INSERT INTO t VALUES (%s)" % ",".join("?" * n), table["rows"])
    agg = AGG[sql["agg"]]
    sel = "c%d" % sql["sel"] if not agg else "%s(c%d)" % (agg, sql["sel"])
    where, args = [], []
    for c, o, v in sql["conds"]:
        where.append("c%d %s ?" % (c, COND[o]))
        args.append(v)
    q = "SELECT %s FROM t" % sel + (" WHERE " + " AND ".join(where) if where else "")
    try:
        out = db.execute(q, args).fetchall()
    except Exception:
        return None
    return sorted(repr(r) for r in out)


def _sql_mutants(sql, table, rng):
    out = []
    n = len(table["header"])
    real = [i for i in range(n) if table["types"][i] == "real"]
    aggs = [a for a in range(6) if a != sql["agg"] and (sql["sel"] in real or a in (0, 3))]
    for a in rng.sample(aggs, min(2, len(aggs))):
        out.append(dict(sql, agg=a))
    others = [i for i in range(n) if i != sql["sel"] and (not sql["agg"] or sql["agg"] == 3 or i in real)]
    if others:
        out.append(dict(sql, sel=rng.choice(others)))
    for k, (c, o, v) in enumerate(sql["conds"]):
        conds = [list(x) for x in sql["conds"]]
        vals = sorted({r[c] for r in table["rows"]} - {v}, key=str)
        if vals:
            conds[k] = [c, o, rng.choice(vals)]
            out.append(dict(sql, conds=conds))
        if isinstance(v, (int, float)):
            conds = [list(x) for x in sql["conds"]]
            conds[k] = [c, {0: 1, 1: 2, 2: 1}[o], v]
            out.append(dict(sql, conds=conds))
    return out


def _wikisql_rows(rng, kind):
    for split_src, split in (("train", "train"), ("dev", "val"), ("test", "val")):
        qs, tables = _wikisql_split(split_src)
        for ex in qs:
            tab = tables[ex["table_id"]]
            if not 2 <= len(tab["rows"]) <= 25 or len(tab["header"]) > 8:
                continue
            gold_res = _run_sql(ex["sql"], tab)
            if not gold_res or gold_res == ["(None,)"]:
                continue
            md = "| " + " | ".join(tab["header"]) + " |\n" + "\n".join(
                "| " + " | ".join(str(x) for x in r) + " |" for r in tab["rows"])
            muts = []
            for m in _sql_mutants(ex["sql"], tab, rng):
                res = _run_sql(m, tab)
                if res is not None:
                    muts.append((m, res == gold_res))
            wrong = [m for m, same in muts if not same]
            if kind == "check":
                cand = [(ex["sql"], 1)] + ([(rng.choice(wrong), 0)] if wrong else [])
                for sql, lab in cand:
                    state = {"table": md, "question": ex["question"], "sql": _sql_text(sql, tab["header"])}
                    yield split, json.dumps(state, ensure_ascii=False), \
                        ts._noul("Does this SQL query correctly answer the question?"), lab, None
            elif wrong:
                w = rng.choice(wrong)
                gold = rng.randrange(2)
                a, b = (ex["sql"], w) if gold == 0 else (w, ex["sql"])
                state = {"table": md, "question": ex["question"], "query_A": _sql_text(a, tab["header"]),
                         "query_B": _sql_text(b, tab["header"])}
                q = {"type": "choice", "instructions": "Which SQL query correctly answers the question?",
                     "criteria": ["query A", "query B"]}
                yield split, json.dumps(state, ensure_ascii=False), q, gold, None


def wikisql_check(rng) -> Iterator[ts.Row]:
    yield from _wikisql_rows(rng, "check")


def wikisql_pair(rng) -> Iterator[ts.Row]:
    yield from _wikisql_rows(rng, "pair")


